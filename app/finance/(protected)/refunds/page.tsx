function normalizeStatus(value: string | null | undefined) {
  return String(value || "").trim().toLowerCase()
}

function titleCaseStatus(value: string | null | undefined) {
  const normalized = normalizeStatus(value)
  if (!normalized) return "-"

  return normalized
    .split(/[\s_-]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ")
}

function resolveBookingStatusLabel(status: string | null | undefined) {
  const normalized = normalizeStatus(status)
  if (normalized === "cancelled_due_overdue_final_payment") return "Dibatalkan: pelunasan lewat H-3"
  return titleCaseStatus(status)
}

function resolveRefundReasonCodeLabel(code: string | null | undefined) {
  const normalized = normalizeStatus(code)
  if (normalized === "final_payment_overdue_auto_review") return "Review otomatis: DP overdue H-3"
  return code || "-"
}

function isAutoGeneratedRefund(refund: RefundRow) {
  return Boolean(refund.metadata?.autoGenerated)
}

function isRefundMatchingFilter(refund: RefundRow, filter: string) {
  if (filter === "auto-review") {
    return isAutoGeneratedRefund(refund)
  }

  if (filter === "manual") {
    return !isAutoGeneratedRefund(refund)
  }

  return true
}

function formatMoney(value: number | null | undefined) {
  return `Rp ${Number(value || 0).toLocaleString("id-ID")}`
}

function formatDate(value: string | null | undefined) {
  if (!value) return "-"
  const date = new Date(value)
  if (Number.isNaN(date.getTime())) return value
  return date.toLocaleString("id-ID", {
    day: "2-digit",
    month: "short",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  })
}

function statusTone(status: string | null | undefined) {
  const normalized = normalizeStatus(status)
  if (normalized === "refund_paid" || normalized === "refund_reconciled") {
    return "border-emerald-200 bg-emerald-50 text-emerald-700"
  }
  if (normalized === "refund_rejected" || normalized === "refund_failed") {
    return "border-rose-200 bg-rose-50 text-rose-700"
  }
  if (
    normalized === "refund_approved" ||
    normalized === "refund_processing_midtrans" ||
    normalized === "refund_processing_bank"
  ) {
    return "border-sky-200 bg-sky-50 text-sky-700"
  }
  if (normalized === "refund_closed") {
    return "border-slate-200 bg-slate-100 text-slate-700"
  }
  return "border-amber-200 bg-amber-50 text-amber-700"
}

function renderMetadataText(
  metadata: Record<string, unknown> | null | undefined,
  key: string,
  fallback = "-",
) {
  const value = metadata?.[key]
  return typeof value === "string" && value.trim() ? value.trim() : fallback
}

